#!/usr/bin/env node
// Refreshes js/bank-holidays-data.js from the government's free feed
// (https://www.gov.uk/bank-holidays.json): England & Wales, Scotland and
// Northern Ireland, from this year on. The feed covers about two years
// ahead, so run this once a year (then stamp, verify and deploy as usual).
// Run: node scripts/update-bank-holidays.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const res = await fetch("https://www.gov.uk/bank-holidays.json");
if (!res.ok) throw new Error(`gov.uk said ${res.status}`);
const feed = await res.json();
const from = `${new Date().getFullYear()}-01-01`;
const out = {};
for (const [region, data] of Object.entries(feed)) {
  out[region] = Object.fromEntries(data.events.filter(e => e.date >= from).map(e => [e.date, e.title]));
}
const last = Object.values(out).flatMap(r => Object.keys(r)).sort().pop();
const body = `// UK bank holidays (generated by scripts/update-bank-holidays.mjs from
// https://www.gov.uk/bank-holidays.json, Open Government Licence). Don't edit
// by hand; run the script once a year. Covers ${from} to ${last}.
window.BANK_HOLIDAYS_DATA = ${JSON.stringify({ until: last, regions: out }, null, 0)};
`;
fs.writeFileSync(path.join(ROOT, "js/bank-holidays-data.js"), body);
console.log(`Wrote js/bank-holidays-data.js: ${Object.entries(out).map(([r, d]) => `${r} ${Object.keys(d).length}`).join(", ")}; up to ${last}`);
