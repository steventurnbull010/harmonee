#!/usr/bin/env node
// Refreshes js/bank-holidays-data.js from the government's free feed
// (https://www.gov.uk/bank-holidays.json): England & Wales, Scotland and
// Northern Ireland, from this year on. The feed covers about two years
// ahead, so run this once a year (then stamp, verify and deploy as usual).
// Run: node scripts/update-bank-holidays.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const res = await fetch("https://www.gov.uk/bank-holidays.json");
if (!res.ok) throw new Error(`gov.uk said ${res.status}`);
const feed = await res.json();
const from = `${new Date().getFullYear()}-01-01`;
const out = {};
// A substitute day (Boxing Day on a Saturday, so Monday off) is listed under
// the holiday's own name: say it's the day off for it, or it looks like a
// mistake ("Boxing Day" on 28 December)
const isSub = (e) => /substitute/i.test(e.notes || "");
const nameOf = (e) => isSub(e) ? `Day off for ${e.title}` : e.title;
// ...and the holiday still shows on its own date ("Boxing Day" on Saturday
// 26th), as a day rather than a bank holiday. The feed only has the day off,
// so the real date comes from the holiday's name.
const REAL_DATE = { "christmas day": "12-25", "boxing day": "12-26", "new year’s day": "01-01", "new year's day": "01-01", "2nd january": "01-02", "st andrew’s day": "11-30", "st patrick’s day": "03-17", "battle of the boyne (orangemen’s day)": "07-12" };
const days = {};
for (const [region, data] of Object.entries(feed)) {
  const mine = data.events.filter(e => e.date >= from);
  out[region] = Object.fromEntries(mine.map(e => [e.date, nameOf(e)]));
  days[region] = {};
  mine.filter(isSub).forEach(e => {
    const md = REAL_DATE[e.title.toLowerCase()];
    if (!md) { console.warn(`No real date known for the substitute "${e.title}" (${e.date})`); return; }
    days[region][`${e.date.slice(0, 4)}-${md}`] = { name: e.title, dayOff: e.date };
  });
}
const last = Object.values(out).flatMap(r => Object.keys(r)).sort().pop();
const body = `// UK bank holidays (generated by scripts/update-bank-holidays.mjs from
// https://www.gov.uk/bank-holidays.json, Open Government Licence). Don't edit
// by hand; run the script once a year. Covers ${from} to ${last}.
window.BANK_HOLIDAYS_DATA = ${JSON.stringify({ until: last, regions: out, days }, null, 0)};
`;
fs.writeFileSync(path.join(ROOT, "js/bank-holidays-data.js"), body);
console.log(`Wrote js/bank-holidays-data.js: ${Object.entries(out).map(([r, d]) => `${r} ${Object.keys(d).length}`).join(", ")}; up to ${last}`);
